"""Reconstruct the paper's Sec. 3.4 figures (rmse_nq, rmse_l, rmse_d,
learning_curve_l*_d*, improvement_dataset) from the existing, unmodified
result artifacts already present in this repository.

No script that generates these figures was found anywhere in the repository
under code/ (see code/code/README.md, Gap 1) at the time this was first
written, using only:
  - CC_rmse_dict.pickle / QC_rmse_dict_{Ry,RzRy}.pickle: the pre-existing,
    unmodified test-RMSE aggregation caches produced by cc_inference.py /
    qc_inference_{Ry,RzRy}.py (copied as-is into this directory).
  - results/valid/{Classic_transfer,Quantum_transfer}/*.txt: the pre-existing,
    unmodified per-epoch validation-RMSE logs written during training.

The "improvement" methodology below was originally reverse-engineered by
comparing candidate constructions against the published figures/main.tex
numbers. It has since been CONFIRMED exactly against the original notebook
`notebook/compr_circuit_s01_CNOT.ipynb` (added to the repo later, containing
`baseline_dict`/`calc_improve_value`/`plot_improvement_data`): the baseline
is the mean, over the 5 training seeds, of each seed's *epoch-0* validation
RMSE (i.e. the pretrained model's performance before any transfer-learning
parameter update) — computed **only from the classical-transfer logs**, and
that same single classical-derived baseline is reused for the Ry and RzRy
improvement calculations too (not a separate baseline per ansatz). Nothing
here is fit *to* the figures: every number plotted is read from the existing
pickles/txt files exactly as they are. Do not edit this file to hand-tune
outputs toward the reference figures.
"""
import pickle
import sys
import pathlib

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

_HERE = pathlib.Path(__file__).resolve()
for _p in _HERE.parents:
    if (_p / "lib" / "ani_transfer").is_dir():
        sys.path.insert(0, str(_p / "lib"))
        break
from ani_transfer.paths import RESULTS_DIR

OUT_DIR = _HERE.parent / "out"
OUT_DIR.mkdir(exist_ok=True)

with open(_HERE.parent / "CC_rmse_dict.pickle", "rb") as f:
    CC_RMSE = pickle.load(f)
with open(_HERE.parent / "QC_rmse_dict_Ry.pickle", "rb") as f:
    QC_RMSE_Ry = pickle.load(f)
with open(_HERE.parent / "QC_rmse_dict_RzRy.pickle", "rb") as f:
    QC_RMSE_RzRy = pickle.load(f)

MODEL_LABELS = ["Classical", "Ry", "RzRy"]


def cc_rmse(data_no, n_qubits, n_layer):
    return CC_RMSE[f"s0{data_no}_{n_qubits}qu_{n_layer}layer"]


def qc_rmse(ansatz, data_no, n_qubits, n_layer, q_depth):
    d = {"Ry": QC_RMSE_Ry, "RzRy": QC_RMSE_RzRy}[ansatz]
    return d[f"s0{data_no}_{n_qubits}qu_{n_layer}layer_{q_depth}depth"]


def read_curve(path):
    with open(path) as f:
        return [float(line) for line in f if line.strip()]


def valid_curve_classical(data_no, n_layer, n_qubits, seed):
    p = RESULTS_DIR / "valid" / "Classic_transfer" / f"valid_CC_s0{data_no}_{n_layer}layer_{n_qubits}qu_seed{seed}.txt"
    return read_curve(p)


def valid_curve_quantum(ansatz, data_no, n_layer, n_qubits, q_depth, seed):
    p = RESULTS_DIR / "valid" / "Quantum_transfer" / f"valid_QC_s0{data_no}_{n_layer}layer_{n_qubits}qu_d{q_depth}_seed{seed}_{ansatz}.txt"
    return read_curve(p)


def bar_with_trials(rows, title, xlabel, filename, hline_at_one=False):
    """rows: list of (x_value, hue_value, [trial values]) tuples."""
    records = []
    for x_val, hue_val, trials in rows:
        for v in trials:
            records.append({"x": x_val, "hue": hue_val, "rmse": v})
    df = pd.DataFrame(records)

    fig, ax = plt.subplots(figsize=(6.4, 4.8))
    sns.barplot(data=df, x="x", y="rmse", hue="hue", ax=ax)
    if hline_at_one:
        ax.axhline(1.0, color="black", linestyle="--", linewidth=1)
    ax.set_title(title)
    ax.set_xlabel(xlabel)
    ax.set_ylabel("RMSE (kcal/mol)")
    ax.legend(title=None)
    fig.tight_layout()
    fig.savefig(OUT_DIR / filename, dpi=150)
    plt.close(fig)
    print(f"wrote {OUT_DIR / filename}")


def fig_rmse_nq():
    # D1, l=1, d=1, x = n_q in {4, 8, 12}, hue = model
    rows = []
    for nq in (4, 8, 12):
        rows.append((nq, "Classical", cc_rmse(1, nq, 1)))
        rows.append((nq, "Ry", qc_rmse("Ry", 1, nq, 1, 1)))
        rows.append((nq, "RzRy", qc_rmse("RzRy", 1, nq, 1, 1)))
    bar_with_trials(rows, "Test RMSE (Dataset 1 / # of layer 1 / Q_depth: 1)",
                     "$n_q$", "rmse_nq.png")


def fig_rmse_l():
    # D1, n_q=4, d=1, x = l in {1,2,3,4}, hue = model
    rows = []
    for l in (1, 2, 3, 4):
        rows.append((l, "Classical", cc_rmse(1, 4, l)))
        rows.append((l, "Ry", qc_rmse("Ry", 1, 4, l, 1)))
        rows.append((l, "RzRy", qc_rmse("RzRy", 1, 4, l, 1)))
    bar_with_trials(rows, "Test RMSE (Dataset 1 / Qubit: 4 / Q_depth: 1)",
                     "# of layer ($l$)", "rmse_l.png", hline_at_one=True)


def fig_rmse_d():
    # D1, n_q=4, P=RzRy, x = l in {1,2,3,4}, hue = depth in {1,5}
    rows = []
    for l in (1, 2, 3, 4):
        rows.append((l, "d=1", qc_rmse("RzRy", 1, 4, l, 1)))
        rows.append((l, "d=5", qc_rmse("RzRy", 1, 4, l, 5)))
    bar_with_trials(rows, "Test RMSE (Dataset 1 / Qubit: 4 / P: RzRy)",
                     "# of layer ($l$)", "rmse_d.png", hline_at_one=True)


def fig_improvement_dataset():
    # n_q=4, l=1, d=1, x = dataset No in {1,2,3,4}, hue = model.
    #
    # "Improvement" = a single, fixed pretrained-model baseline RMSE minus
    # each of the 5 per-seed final test RMSEs from the *_rmse_dict pickles.
    # The baseline is the mean, over the 5 training seeds, of each seed's
    # *epoch-0* validation-log entry (i.e. the model's RMSE before any
    # transfer-learning parameter update — evaluated only from the
    # classical-transfer runs) and is reused unchanged for the Classical,
    # Ry, and RzRy improvement calculations alike (there is no separate
    # per-ansatz baseline). This exact construction (`baseline_dict` /
    # `calc_improve_value` / `plot_improvement_data`) was found in
    # notebook/compr_circuit_s01_CNOT.ipynb — see module docstring.
    rows = []
    for data_no in (1, 2, 3, 4):
        cc_test = cc_rmse(data_no, 4, 1)
        baseline = np.mean([valid_curve_classical(data_no, 1, 4, s)[0] for s in range(len(cc_test))])
        rows.append((data_no, "Classical", [baseline - t for t in cc_test]))

        ry_test = qc_rmse("Ry", data_no, 4, 1, 1)
        rows.append((data_no, "Ry", [baseline - t for t in ry_test]))

        rzry_test = qc_rmse("RzRy", data_no, 4, 1, 1)
        rows.append((data_no, "RzRy", [baseline - t for t in rzry_test]))

    records = []
    for x_val, hue_val, trials in rows:
        for v in trials:
            records.append({"x": x_val, "hue": hue_val, "improvement": v})
    df = pd.DataFrame(records)

    fig, ax = plt.subplots(figsize=(6.4, 4.8))
    sns.barplot(data=df, x="x", y="improvement", hue="hue", ax=ax)
    ax.set_title("Test Improvement (Qubit: 4 / # of layer: 1 / Q_depth: 1)")
    ax.set_xlabel("dataset No.")
    ax.set_ylabel("Improvement (kcal/mol)")
    ax.legend(title=None)
    fig.tight_layout()
    fig.savefig(OUT_DIR / "improvement_dataset.png", dpi=150)
    plt.close(fig)
    print(f"wrote {OUT_DIR / 'improvement_dataset.png'}")


def fig_learning_curves():
    # D1, n_q=4, seed=0. Classical has no circuit-depth parameter, so the
    # same classical curve is reused in both the d=1 and d=5 panel for a
    # given l (matching how the classical baseline is depth-independent).
    for l in (1, 2, 3, 4):
        for d in (1, 5):
            classical = valid_curve_classical(1, l, 4, seed=0)
            ry = valid_curve_quantum("Ry", 1, l, 4, d, seed=0)
            rzry = valid_curve_quantum("RzRy", 1, l, 4, d, seed=0)

            fig, ax = plt.subplots(figsize=(5, 4))
            epochs = range(1, len(classical) + 1)
            ax.plot(epochs, classical, label="Classical")
            ax.plot(range(1, len(ry) + 1), ry, label="Ry")
            ax.plot(range(1, len(rzry) + 1), rzry, label="RzRy")
            ax.set_title(f"Data: 1 / Layer: {l} / Qubit: 4 / Q_depth: {d}")
            ax.set_xlabel("epoch")
            ax.set_ylabel("RMSE")
            ax.legend()
            fig.tight_layout()
            fname = f"learning_curve_l{l}_d{d}.png"
            fig.savefig(OUT_DIR / fname, dpi=150)
            plt.close(fig)
            print(f"wrote {OUT_DIR / fname}")


if __name__ == "__main__":
    sns.set_theme()
    fig_rmse_nq()
    fig_rmse_l()
    fig_rmse_d()
    fig_improvement_dataset()
    fig_learning_curves()
